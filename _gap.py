def where(term, n=2):
    """本站教材里提到该词最多的章（标题, 次数）。"""
    hits = []
    for p, s in new.items():
        c = s.count(term)
        if c:
            lv = os.path.basename(os.path.dirname(p))
            hits.append((c, lv + ' · ' + s.split('\n', 1)[0].lstrip('# ').strip()))
    hits.sort(reverse=True)
    return hits[:n]


def loc(term):
    h = where(term)
    return '；'.join('%s（%d 处）' % (t, c) for c, t in h) if h else '—'


